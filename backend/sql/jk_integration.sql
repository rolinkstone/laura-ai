-- =====================================================================
-- INTEGRASI JENDELA KINERJA → LAURA AI
-- Tabel konfigurasi endpoint API + cache data + log sinkronisasi.
-- Idempoten — aman dijalankan berulang.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. jk_api_endpoint — tabel API Jendela Kinerja
--    Setiap baris = satu endpoint JK yang datanya masuk ke knowledge Laura.
--    `token_masa_berlaku_hari` mengatur berapa lama token akses berlaku.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS jk_api_endpoint (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode VARCHAR(50) NOT NULL UNIQUE,
  nama VARCHAR(150) NOT NULL,
  url_path VARCHAR(300) NOT NULL,
  metode VARCHAR(10) NOT NULL DEFAULT 'GET'
    CHECK (metode IN ('GET')),
  auth_mode VARCHAR(20) NOT NULL DEFAULT 'public'
    CHECK (auth_mode IN ('public', 'bearer')),
  -- Parameter query default (JSON), mis. {"tahun": "2026"}
  parameter JSONB NOT NULL DEFAULT '{}'::jsonb,
  -- Export field yang diambil ke knowledge (JSON array), null = semua
  field_ekspor JSONB,
  kategori_kb VARCHAR(100) NOT NULL DEFAULT 'Jendela Kinerja',
  -- Pemetaan model data (JSON) — dipakai perakit teks knowledge
  model_data VARCHAR(40) NOT NULL DEFAULT 'ringkasan'
    CHECK (model_data IN ('ringkasan', 'pilihan', 'daftar_sarana', 'rekap_sampel', 'generik')),
  aktif SMALLINT NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
  urutan INT NOT NULL DEFAULT 0,
  -- ---- Token ----
  token_masa_berlaku_hari INT NOT NULL DEFAULT 30 CHECK (token_masa_berlaku_hari > 0),
  token_terbit_pada TIMESTAMP,
  token_kedaluwarsa_pada TIMESTAMP,
  token_hash VARCHAR(128),
  -- ---- Hasil sinkronisasi terakhir ----
  tersinkron_pada TIMESTAMP,
  tersinkron_status TEXT NOT NULL DEFAULT 'belum'
    CHECK (tersinkron_status IN ('belum', 'sukses', 'gagal')),
  tersinkron_pesan TEXT,
  dokumen_id INT REFERENCES documents(id) ON DELETE SET NULL,
  jumlah_baris INT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_jk_api_aktif ON jk_api_endpoint(aktif, urutan);

-- ---------------------------------------------------------------------
-- 2. jk_sync_log — riwayat setiap penarikan data dari JK
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS jk_sync_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint_id INT REFERENCES jk_api_endpoint(id) ON DELETE CASCADE,
  kode VARCHAR(50) NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('sukses', 'gagal')),
  http_status INT,
  jumlah_baris INT,
  chunk_count INT,
  durasi_ms INT,
  pesan TEXT,
  dipicu_oleh VARCHAR(150),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_jk_sync_log_endpoint ON jk_sync_log(endpoint_id, created_at DESC);

-- ---------------------------------------------------------------------
-- 3. jk_snapshot — payload mentah terakhir per endpoint (audit/debug)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS jk_snapshot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint_id INT REFERENCES jk_api_endpoint(id) ON DELETE CASCADE,
  parameter_kirim JSONB,
  payload JSONB,
  diambil_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_jk_snapshot_endpoint ON jk_snapshot(endpoint_id, diambil_pada DESC);

